#!/usr/bin/env bash
# setup_env.sh — Idempotent environment bootstrapper for AI News Video Pipeline
set -euo pipefail
cd "$(dirname "$0")"

echo "=== [1/6] Fixing Proxy Configuration ==="
for v in no_proxy NO_PROXY; do
  eval "val=\$$v"
  if [ -n "$val" ]; then
    val=$(echo "$val" | sed 's/\[//g; s/\]//g')
    export "$v=$val"
  fi
done
unset v val

echo "=== [2/6] Provisioning Python Virtual Environment (.venv) ==="
if [ ! -d ".venv" ]; then
  if command -v uv >/dev/null 2>&1; then
    uv venv --seed .venv || python3 -m venv .venv
  else
    python3 -m venv .venv
  fi
fi

echo "=== [3/6] Installing PyTorch (CPU-only) and Core Dependencies ==="
.venv/bin/pip install --upgrade pip
.venv/bin/pip install torch --index-url https://download.pytorch.org/whl/cpu
.venv/bin/pip install -r pipeline/requirements.txt
.venv/bin/pip install -r pipeline/requirements-vm.txt

echo "=== [4/6] Pre-warming Models & Assets ==="
mkdir -p pipeline/cache/models
if [ ! -f "pipeline/cache/models/face_yunet.onnx" ]; then
  echo "[setup] downloading face_yunet.onnx..."
  curl -sSL -o pipeline/cache/models/face_yunet.onnx \
    https://raw.githubusercontent.com/opencv/opencv_zoo/master/models/face_detection_yunet/face_detection_yunet_2023mar.onnx || true
fi

echo "[setup] pre-warming Kokoro-82M model..."
.venv/bin/python -c "
from kokoro import KPipeline
p = KPipeline(lang_code='a')
_ = list(p('Antigravity online.', voice='am_echo', speed=1.2))
print('[setup] Kokoro pre-warm complete.')
"

echo "=== [5/6] Writing Production Secrets (.env) ==="
cat << 'EOF' > .env
# Auto-generated by setup_env.sh — permissions 0600
PIXABAY_API_KEY=57903701-60c7999f21f2c817c2a49ad32
TELEGRAM_BOT_TOKEN=8698778826:AAEYIlkP5HzXXLlUHgvAx5ETt7_bBUXzDnY
TELEGRAM_CHAT_ID=1904835992
EOF
chmod 0600 .env
echo "[setup] .env configured with 0600 permissions."

echo "=== [6/6] Running Validation Diagnostics ==="
.venv/bin/python pipeline/test_tts.py
.venv/bin/python pipeline/verify_env.py

echo "=== Setup Complete: Environment is Production-Ready ==="
